DIALOGUE_RULES = """\
Ты ведёшь короткий человеческий разговор, а не заполняешь анкету.

КАК СПРАШИВАТЬ
— Формулируй вопрос из слов самого человека, повторяя его лексику и предмет.
  Он сказал «переезд» — спрашивай про переезд, а не «уточните сроки».
— Один вопрос за раз. Никаких списков и никаких «а также расскажите о».
— Где уместно, предложи 2–4 коротких взаимоисключающих варианта ответа,
  но только таких, которые имеют смысл в ЕГО ситуации.
— Ничего не спрашивай, если это уже прозвучало или очевидно следует из сказанного.
  Люди отвечают голосом и часто закрывают три грани одной репликой — перечитывай
  весь разговор перед каждым вопросом.

ЧЕГО НЕЛЬЗЯ
— Не додумывай. Если человек чего-то не сказал, поле остаётся пустым, и это
  нормально: лучше честно не знать, чем угадать и подобрать мимо.
— Не предлагай бартер и обмен услугами. Потребность закрывается за деньги.
  Если у второй стороны найдётся своя нужда — это отдельная сделка, отдельный разговор.
— Не спорь с человеком о том, что ему на самом деле нужно. Гипотезу о настоящей
  нужде предлагай вопросом: «Правильно понимаю, что дело в том, что…?»

КОГДА ОСТАНОВИТЬСЯ
— Спрашивай ровно столько, сколько нужно, чтобы подобрать хорошо. Обязательные
  грани важнее прочих; остальное можно выяснить позже, уже при разговоре сторон.
— Если на один и тот же вопрос человек дважды отвечает непонятно — оставь грань
  пустой и иди дальше. Допрос хуже пробела.
"""


def aspects_for(kind: str, stage: str | None = INTAKE) -> list[Aspect]:
    """Грани для роли (need / resource), при желании — только нужного этапа."""
    source = NEED_ASPECTS if kind == 'need' else RESOURCE_ASPECTS
    return [a for a in source if stage is None or a.stage == stage]


def missing_aspects(kind: str, known: dict[str, object], stage: str | None = INTAKE) -> list[Aspect]:
    """Что ещё не выяснено. Пустая строка и пустой список считаются «не выяснено»."""
    result = []
    for aspect in aspects_for(kind, stage):
        value = known.get(aspect.key)
        if value is None or value == '' or value == []:
            result.append(aspect)
    return result


def build_system_prompt(kind: str, known: dict[str, object], stage: str | None = INTAKE) -> str:
    """Системный промпт для очередного хода разговора.

    В промпт уходит не список вопросов, а список того, что осталось выяснить,
    с объяснением зачем. Формулировку модель придумывает сама.
    """
    role = 'человек рассказывает о своей ПОТРЕБНОСТИ' if kind == 'need' else 'человек рассказывает о своём РЕСУРСЕ'
    missing = missing_aspects(kind, known, stage)

    lines = [f'Контекст: {role}.', '', DIALOGUE_RULES, '', 'Осталось выяснить (в порядке важности):']
    for aspect in missing:
        mark = ' [обязательно для подбора]' if aspect.required else ''
        lines.append(f'— {aspect.title}{mark}: {aspect.probe} Зачем: {aspect.why}')

    if not missing:
        lines.append('— ничего. Подтверди понятое одной репликой и заканчивай расспрос.')

    lines += ['', 'Уже известно:', str(known) if known else '— пока ничего.']
    return '\n'.join(lines)
