"""Карта интервью: что сервис обязан выяснить о потребности и о ресурсе.

Это одновременно документ для правки и рабочий код: список граней отсюда
уходит в промпт модели, которая ведёт разговор в Telegram.

ГЛАВНОЕ ОТЛИЧИЕ ОТ АНКЕТЫ. Здесь нет готовых текстов вопросов, и это
сделано намеренно. Хранится только то, ЧТО надо выяснить и ЗАЧЕМ.
Формулировку модель придумывает сама, глядя на весь рассказ человека и
повторяя его собственные слова. Поэтому «Расскажите про: сроки?» тут
невозможно в принципе — вместо этого будет «К какому числу нужно успеть
с переездом?», потому что человек сказал именно про переезд.

МОДЕЛЬ ОБМЕНА. Сервис не бартерный. За удовлетворение потребности платят
деньгами — как за услугу, товар или знание. Никакой «встречной ценности»
на входе не спрашивается. Если позже выяснится, что у второй стороны есть
своя потребность, которую первый может закрыть, — это ОТДЕЛЬНАЯ НОВАЯ
СДЕЛКА со своим описанием и своей ценой, а не зачёт и не обмен. Ресурс
никогда не подгоняется под чужую нужду ради того, чтобы вышел бартер.

ФОКУС-ГРУППА. Первыми интервью проходят друзья автора — обычные люди с
самыми разными запросами, от бытовых до профессиональных. Поэтому карта
общая, без отраслевой специфики: специфика приходит из слов человека,
а не из заранее заданной ниши.

ГОЛОС. Отвечают голосом, а значит длинно, сбивчиво и не по порядку — в
одной реплике может оказаться ответ сразу на три грани. Модель обязана
разбирать такой поток и не переспрашивать то, что уже прозвучало.
"""

